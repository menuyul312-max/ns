"""Render actual Godot-exported Nusa skeleton poses with Blender Cycles.

Example:
  blender -b --factory-startup --python tools/render_nusa_motion.py -- \
    --model /path/to/private_user_model.glb \
    --samples-json /path/to/nusa_animation_samples.json \
    --output-dir /path/to/frames --resolution 540 --samples 8

The input poses are generated by export_nusa_animation_samples.gd, so the video
demonstrates real Godot prototype animation tracks, not reauthored keyframes.
"""

import argparse
import json
import math
from pathlib import Path
import sys

import bpy
from mathutils import Matrix, Quaternion, Vector

sys.path.insert(0, str(Path(__file__).resolve().parent))
from render_nusa_preview import point_camera, prepare_scene


# Godot skeletons are Y-up, whereas Blender glTF importer gives Z-up bones.
GODOT_TO_BLENDER = Matrix.Rotation(math.pi / 2.0, 4, "X")


def transform_from_sample(packed):
    x, y, z, w, px, py, pz = packed
    return Matrix.Translation(Vector((px, py, pz))) @ Quaternion((w, x, y, z)).to_matrix().to_4x4()


def key_order(armature, names):
    keys = [armature.pose.bones[name] for name in names if name in armature.pose.bones]
    return sorted(keys, key=lambda bone: len(bone.parent_recursive))


def apply_pose(armature, bone_order, rest, sample):
    for pose_bone in bone_order:
        bone_name = pose_bone.name
        reference = rest[bone_name]
        current = transform_from_sample(sample[bone_name])
        delta = GODOT_TO_BLENDER @ current @ reference.inverted() @ GODOT_TO_BLENDER.inverted()
        pose_bone.matrix = delta @ pose_bone.bone.matrix_local
    bpy.context.view_layer.update()


def make_render(model, sample_file, output_dir, resolution, samples, loops, only, max_frames):
    motion = json.loads(sample_file.read_text(encoding="utf-8"))
    if motion.get("schema") != "nusa_motion_samples_v1":
        raise ValueError("Invalid Godot pose export schema")
    camera, center, height = prepare_scene(model)
    armatures = [obj for obj in bpy.context.scene.objects if obj.type == "ARMATURE"]
    if len(armatures) != 1:
        raise ValueError("Expected one armature, found %s" % len(armatures))
    armature = armatures[0]
    # Imported GLB contains Idle/FaceTest actions. Their F-curves must not
    # override the Godot frame poses at Blender's render-time depsgraph update.
    for obj in bpy.context.scene.objects:
        obj.animation_data_clear()
        if obj.type == "MESH" and obj.data.shape_keys is not None:
            obj.data.shape_keys.animation_data_clear()
    armature.data.pose_position = "POSE"
    names = motion["bones"]
    if not all(name in armature.pose.bones for name in names):
        raise ValueError("Bone names differ between Godot GLB and Blender GLB")
    rest = {name: transform_from_sample(value) for name, value in zip(names, motion["rest_global"])}
    order = key_order(armature, names)
    # Aim through a slight 3/4 view so hands and both feet remain visible.
    angle = math.radians(-21.0)
    dist = height * 3.3
    point_camera(camera,
                 center + Vector((math.sin(angle) * dist, -math.cos(angle) * dist, height * 0.12)),
                 center + Vector((0, 0, height * 0.02)))
    camera.data.ortho_scale = height * 1.44

    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.samples = samples
    bpy.context.view_layer.cycles.use_denoising = False
    scene.render.resolution_x = resolution
    scene.render.resolution_y = resolution
    scene.render.resolution_percentage = 100
    scene.render.image_settings.file_format = "PNG"
    scene.view_settings.view_transform = "AgX"
    output_dir.mkdir(parents=True, exist_ok=True)
    frame_idx = 0
    manifest = {"fps": int(motion["fps"]), "clips": [], "source": motion["source"]}
    for clip in motion["clips"]:
        if only and clip["name"] not in only:
            continue
        start_idx = frame_idx
        sampled = clip["frames"]
        for cycle in range(loops):
            for index, data in enumerate(sampled):
                sample = dict(zip(names, data["pose"]))
                apply_pose(armature, order, rest, sample)
                if index == 3 and cycle == 0:
                    p = armature.pose.bones.get("LeftUpperArm")
                    if p is not None:
                        print("NUSA_POSE_CHECK", clip["name"], tuple(round(v, 4) for v in p.matrix.to_translation()))
                scene.render.filepath = str(output_dir / f"motion_{frame_idx:05}.png")
                bpy.ops.render.render(write_still=True)
                frame_idx += 1
                if max_frames and frame_idx >= max_frames:
                    break
            if max_frames and frame_idx >= max_frames:
                break
        manifest["clips"].append({"name": clip["name"], "start_frame": start_idx,
                                  "end_frame": frame_idx, "category":
                                  "locomotion" if len(manifest["clips"]) < 8 else "action"})
        print(f"NUSA_MOTION_RENDER {clip['name']} {frame_idx-start_idx} frames")
        if max_frames and frame_idx >= max_frames:
            break
    manifest["total_frames"] = frame_idx
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print("NUSA_MOTION_RENDER_DONE", str(output_dir), "frames=", frame_idx)


if __name__ == "__main__":
    if "--" not in sys.argv:
        raise SystemExit("Use -- followed by --model, --samples-json, --output-dir")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument("--samples-json", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--resolution", type=int, default=480)
    parser.add_argument("--samples", type=int, default=8)
    parser.add_argument("--loops", type=int, default=2)
    parser.add_argument("--only", nargs="*", default=[])
    parser.add_argument("--max-frames", type=int, default=0)
    args = parser.parse_args(sys.argv[sys.argv.index("--") + 1:])
    make_render(args.model, args.samples_json, args.output_dir, args.resolution,
                args.samples, args.loops, args.only, args.max_frames)
